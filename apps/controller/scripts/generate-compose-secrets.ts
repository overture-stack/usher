// Writes every secret read by compose.yaml into .env beside it, each made fresh: the database
// passwords, the Controller's key-encryption key and cursor key, and Keycloak's administrator
// password. Git ignores the file, and only its owner may read it. An existing file is replaced only
// when --force is given, since the database volume keeps the passwords it was created with. Nothing
// written to the terminal holds a value.
//
//     node scripts/generate-compose-secrets.ts [--force]
import { randomBytes } from 'node:crypto';
import { rmSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { parseArgs } from 'node:util';

const SECRETS_FILE = resolve(import.meta.dirname, '..', '.env');

const SECRET_NAMES: readonly string[] = [
	'KEYCLOAK_ADMIN_PASSWORD',
	'POSTGRES_SUPERUSER_PASSWORD',
	'USHER_CURSOR_KEY',
	'USHER_DATABASE_PASSWORD',
	'USHER_KEY_ENCRYPTION_KEY',
	'USHER_SCHEMA_MIGRATION_DATABASE_PASSWORD',
];

// 32 random bytes as 43 unpadded base64url characters: the canonical form of the Controller's keys,
// and a password needing no quoting in a URL, a shell or an environment file.
const freshSecret = (): string => randomBytes(32).toString('base64url');

const fileText = (): string =>
	[
		'# Generated by scripts/generate-compose-secrets.ts for compose.yaml. Never commit it.',
		...SECRET_NAMES.map((name) => `${name}=${freshSecret()}`),
		'',
	].join('\n');

const isExistingFile = (failure: unknown): boolean =>
	failure instanceof Error && 'code' in failure && failure.code === 'EEXIST';

const {
	values: { force },
} = parseArgs({ options: { force: { default: false, type: 'boolean' } } });

if (force) {
	rmSync(SECRETS_FILE, { force: true });
}

try {
	writeFileSync(SECRETS_FILE, fileText(), { flag: 'wx', mode: 0o600 });
	process.stdout.write(`Wrote ${SECRETS_FILE}, holding ${SECRET_NAMES.join(', ')}.\n`);
} catch (failure) {
	if (isExistingFile(failure)) {
		process.stderr.write(
			`${SECRETS_FILE} exists, and was left as it is. To replace it, run docker compose --profile image down --volumes first, since the database keeps the passwords it was created with, then run this again with --force.\n`,
		);
		process.exitCode = 1;
	} else {
		throw failure;
	}
}
