/** One column of a table, as the database's catalogue describes it. */
export interface CatalogueColumn {
	name: string;
	notNull: boolean;
	/** The type as PostgreSQL's `format_type` writes it, such as `timestamp with time zone`. */
	type: string;
}

/** One foreign key of a table, its columns in the key's own order. */
export interface CatalogueForeignKey {
	columns: readonly string[];
	name: string;
	referencedColumns: readonly string[];
	referencedTable: string;
}

/** One table of the schema, with what an entity-relationship diagram shows of it. */
export interface CatalogueTable {
	/** In the table's own column order. */
	columns: readonly CatalogueColumn[];
	foreignKeys: readonly CatalogueForeignKey[];
	name: string;
	primaryKey: readonly string[];
	/** The column sets of every unique constraint and every unique index covering all rows. */
	uniqueColumnSets: readonly (readonly string[])[];
}

/** A part of the schema drawn as one diagram, under its own heading, its tables in drawing order. */
export interface DiagramArea {
	tables: readonly string[];
	title: string;
}

const GENERATED_NOTE =
	"<!-- Generated by apps/controller/scripts/generate-erd.ts from the Controller's migrations. Regenerate it rather than editing it. -->";

// The page's title and the line under it, written for where the page lives: beside schema.md.
const HEADING = [
	'# Schema diagrams',
	'',
	"The Controller's tables by area, as its migrations create them. What each table holds, and why, is in [schema.md](schema.md).",
];

const AREAS_FILE = 'scripts/erd/areas.ts';

const SHORT_TYPES: Readonly<Record<string, string>> = Object.freeze({
	'character varying': 'varchar',
	'time with time zone': 'timetz',
	'time without time zone': 'time',
	'timestamp with time zone': 'timestamptz',
	'timestamp without time zone': 'timestamp',
});

/**
 * Writes a PostgreSQL type as the one word a Mermaid attribute type must be: the short form of a
 * type of several words, the words of any other joined by `_`, an array marked by an `_array`
 * suffix, and any length or precision dropped.
 *
 * @param type the type as PostgreSQL's `format_type` writes it.
 */
export const mermaidType = (type: string): string => {
	const isArray = type.endsWith('[]');
	const element = (isArray ? type.slice(0, -2) : type).replace(/\(.*\)/, '').trim();
	const word = (SHORT_TYPES[element] ?? element).replaceAll(' ', '_');
	return isArray ? `${word}_array` : word;
};

const sameColumns = (first: readonly string[], second: readonly string[]): boolean =>
	first.length === second.length && first.every((column) => second.includes(column));

const keyMarks = (table: CatalogueTable, column: string): string => {
	const marks = [
		...(table.primaryKey.includes(column) ? ['PK'] : []),
		...(table.foreignKeys.some((key) => key.columns.includes(column)) ? ['FK'] : []),
	];
	return marks.length > 0 ? ` ${marks.join(', ')}` : '';
};

const entityLines = (table: CatalogueTable): string[] => [
	`  ${table.name} {`,
	...table.columns.map(
		(column) =>
			`    ${mermaidType(column.type)} ${column.name}${keyMarks(table, column.name)}${column.notNull ? '' : ' "nullable"'}`,
	),
	'  }',
];

// Mermaid reads `parent <parent side>--<child side> child`. The parent side says how many parents a
// child row has, and the child side how many child rows one parent has.
const relationshipLine = (table: CatalogueTable, key: CatalogueForeignKey): string => {
	const required = key.columns.every(
		(name) => table.columns.find((column) => column.name === name)?.notNull === true,
	);
	const unique = [table.primaryKey, ...table.uniqueColumnSets].some((columns) => sameColumns(columns, key.columns));
	const parentSide = required ? '||' : '|o';
	const childSide = unique ? 'o|' : 'o{';
	return `  ${key.referencedTable} ${parentSide}--${childSide} ${table.name} : "${key.columns.join(', ')}"`;
};

const areaLines = (area: DiagramArea, byName: ReadonlyMap<string, CatalogueTable>): string[] => {
	const tables = area.tables.flatMap((name) => {
		const found = byName.get(name);
		return found ? [found] : [];
	});
	return [
		`## ${area.title}`,
		'',
		'```mermaid',
		'erDiagram',
		...tables.flatMap(entityLines),
		...tables.flatMap((table) => table.foreignKeys.map((key) => relationshipLine(table, key))),
		'```',
		'',
	];
};

const sortedNames = (names: Iterable<string>): string => [...new Set(names)].toSorted().join(', ');

const checkAreas = (tables: readonly CatalogueTable[], areas: readonly DiagramArea[]): void => {
	const named = areas.flatMap((area) => area.tables);
	const inSchema = new Set(tables.map((table) => table.name));
	const unplaced = [...inSchema].filter((name) => !named.includes(name));
	if (unplaced.length > 0) {
		throw new Error(
			`Every table belongs to one area, and these belong to none: ${sortedNames(unplaced)}. Add each to an area in ${AREAS_FILE}.`,
		);
	}
	const absent = named.filter((name) => !inSchema.has(name));
	if (absent.length > 0) {
		throw new Error(
			`Every table an area names is in the schema, and these are not: ${sortedNames(absent)}. Remove each from ${AREAS_FILE}, or rename it.`,
		);
	}
	const repeated = named.filter((name, index) => named.indexOf(name) !== index);
	if (repeated.length > 0) {
		throw new Error(
			`Every table belongs to one area, and these belong to more than one: ${sortedNames(repeated)}. Keep each in one area in ${AREAS_FILE}.`,
		);
	}
};

/**
 * Writes the schema as Markdown: a note saying it is generated, the page's title and a pointer to
 * schema.md, then each area's heading over a Mermaid entity-relationship diagram of its tables. A foreign key is drawn in its own table's area,
 * so a table it references in another area appears there by name alone. Every table must belong to
 * exactly one area, and every table an area names must be in the schema; otherwise it throws,
 * naming each table at fault.
 *
 * @param tables the schema's tables, as the catalogue describes them.
 * @param areas the parts of the schema, in the order they are drawn.
 */
export const renderAreas = (tables: readonly CatalogueTable[], areas: readonly DiagramArea[]): string => {
	checkAreas(tables, areas);
	const byName = new Map(tables.map((table) => [table.name, table]));
	return [GENERATED_NOTE, '', ...HEADING, '', ...areas.flatMap((area) => areaLines(area, byName))].join('\n');
};
