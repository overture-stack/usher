import assert from 'node:assert/strict';
import { suite, test } from 'node:test';

import { type CatalogueTable, type DiagramArea, mermaidType, renderAreas } from './diagram.js';

const table = (name: string, overrides: Partial<Omit<CatalogueTable, 'name'>> = {}): CatalogueTable => ({
	columns: [{ name: 'id', notNull: true, type: 'uuid' }],
	foreignKeys: [],
	name,
	primaryKey: ['id'],
	uniqueColumnSets: [],
	...overrides,
});

const users = table('users', {
	columns: [
		{ name: 'id', notNull: true, type: 'uuid' },
		{ name: 'email', notNull: false, type: 'text' },
	],
});

const identities = table('user_identities', {
	columns: [
		{ name: 'id', notNull: true, type: 'uuid' },
		{ name: 'user_id', notNull: true, type: 'uuid' },
		{ name: 'issued_at', notNull: true, type: 'timestamp with time zone' },
	],
	foreignKeys: [
		{
			columns: ['user_id'],
			name: 'user_identities_user_id_fkey',
			referencedColumns: ['id'],
			referencedTable: 'users',
		},
	],
});

suite('renderAreas', () => {
	test('draws each area as a heading over its own diagram, holding its tables with their columns and keys', () => {
		const areas: DiagramArea[] = [{ tables: ['users', 'user_identities'], title: 'Principals' }];

		const markdown = renderAreas([users, identities], areas);

		assert.equal(
			markdown,
			[
				"<!-- Generated by apps/controller/scripts/generate-erd.ts from the Controller's migrations. Regenerate it rather than editing it. -->",
				'',
				'# Schema diagrams',
				'',
				"The Controller's tables by area, as its migrations create them. What each table holds, and why, is in [schema.md](schema.md).",
				'',
				'## Principals',
				'',
				'```mermaid',
				'erDiagram',
				'  users {',
				'    uuid id PK',
				'    text email "nullable"',
				'  }',
				'  user_identities {',
				'    uuid id PK',
				'    uuid user_id FK',
				'    timestamptz issued_at',
				'  }',
				'  users ||--o{ user_identities : "user_id"',
				'```',
				'',
			].join('\n'),
		);
	});

	test('notes a column that may be null as nullable, after its keys, and leaves a required one unmarked', () => {
		const invitations = table('invitations', {
			columns: [
				{ name: 'id', notNull: true, type: 'uuid' },
				{ name: 'user_id', notNull: false, type: 'uuid' },
			],
			foreignKeys: [
				{
					columns: ['user_id'],
					name: 'invitations_user_id_fkey',
					referencedColumns: ['id'],
					referencedTable: 'users',
				},
			],
		});

		const markdown = renderAreas([users, invitations], [{ tables: ['users', 'invitations'], title: 'All' }]);

		assert.match(markdown, /^ {4}uuid user_id FK "nullable"$/mu);
		assert.match(markdown, /^ {4}uuid id PK$/mu);
	});

	test("draws a foreign key into another area's table, which that table's own area describes", () => {
		const areas: DiagramArea[] = [
			{ tables: ['users'], title: 'Principals' },
			{ tables: ['user_identities'], title: 'Identities' },
		];

		const markdown = renderAreas([users, identities], areas);
		const identitiesArea = markdown.slice(markdown.indexOf('## Identities'));

		assert.match(identitiesArea, /users \|\|--o\{ user_identities : "user_id"/);
		assert.doesNotMatch(identitiesArea, /users \{/);
	});

	test('draws the parent as exactly one when every foreign key column is required, and as zero or one when any may be null', () => {
		const optional = table('invitations', {
			columns: [
				{ name: 'id', notNull: true, type: 'uuid' },
				{ name: 'user_id', notNull: false, type: 'uuid' },
			],
			foreignKeys: [
				{
					columns: ['user_id'],
					name: 'invitations_user_id_fkey',
					referencedColumns: ['id'],
					referencedTable: 'users',
				},
			],
		});
		const areas: DiagramArea[] = [{ tables: ['users', 'user_identities', 'invitations'], title: 'All' }];

		const markdown = renderAreas([users, identities, optional], areas);

		assert.match(markdown, /users \|\|--o\{ user_identities : "user_id"/);
		assert.match(markdown, /users \|o--o\{ invitations : "user_id"/);
	});

	test('draws the child as at most one when its foreign key columns are unique, and as many otherwise', () => {
		const administrators = table('administrators', {
			columns: [
				{ name: 'id', notNull: true, type: 'uuid' },
				{ name: 'user_id', notNull: true, type: 'uuid' },
			],
			foreignKeys: [
				{
					columns: ['user_id'],
					name: 'administrators_user_id_fkey',
					referencedColumns: ['id'],
					referencedTable: 'users',
				},
			],
			uniqueColumnSets: [['user_id']],
		});
		const areas: DiagramArea[] = [{ tables: ['users', 'user_identities', 'administrators'], title: 'All' }];

		const markdown = renderAreas([users, identities, administrators], areas);

		assert.match(markdown, /users \|\|--o\| administrators : "user_id"/);
		assert.match(markdown, /users \|\|--o\{ user_identities : "user_id"/);
	});

	test('draws the child as at most one when its foreign key columns are its primary key', () => {
		const settings = table('user_settings', {
			columns: [{ name: 'user_id', notNull: true, type: 'uuid' }],
			foreignKeys: [
				{
					columns: ['user_id'],
					name: 'user_settings_user_id_fkey',
					referencedColumns: ['id'],
					referencedTable: 'users',
				},
			],
			primaryKey: ['user_id'],
		});

		const markdown = renderAreas([users, settings], [{ tables: ['users', 'user_settings'], title: 'All' }]);

		assert.match(markdown, /users \|\|--o\| user_settings : "user_id"/);
		assert.match(markdown, /uuid user_id PK, FK/);
	});

	test('labels a foreign key with every column it spans, in order', () => {
		const resources = table('application_resources', {
			columns: [
				{ name: 'application_id', notNull: true, type: 'uuid' },
				{ name: 'resource_id', notNull: true, type: 'uuid' },
			],
			primaryKey: ['application_id', 'resource_id'],
		});
		const grants = table('grants', {
			columns: [
				{ name: 'id', notNull: true, type: 'uuid' },
				{ name: 'application_id', notNull: true, type: 'uuid' },
				{ name: 'resource_id', notNull: true, type: 'uuid' },
			],
			foreignKeys: [
				{
					columns: ['application_id', 'resource_id'],
					name: 'grants_served_fkey',
					referencedColumns: ['application_id', 'resource_id'],
					referencedTable: 'application_resources',
				},
			],
		});

		const markdown = renderAreas(
			[resources, grants],
			[{ tables: ['application_resources', 'grants'], title: 'All' }],
		);

		assert.match(markdown, /application_resources \|\|--o\{ grants : "application_id, resource_id"/);
	});

	test('draws a table that references itself', () => {
		const grants = table('grants', {
			columns: [
				{ name: 'id', notNull: true, type: 'uuid' },
				{ name: 'replaces_id', notNull: false, type: 'uuid' },
			],
			foreignKeys: [
				{
					columns: ['replaces_id'],
					name: 'grants_replaces_id_fkey',
					referencedColumns: ['id'],
					referencedTable: 'grants',
				},
			],
		});

		const markdown = renderAreas([grants], [{ tables: ['grants'], title: 'Grants' }]);

		assert.match(markdown, /grants \|o--o\{ grants : "replaces_id"/);
	});

	test('refuses a table no area names, naming each such table', () => {
		const areas: DiagramArea[] = [{ tables: ['users'], title: 'Principals' }];

		assert.throws(() => renderAreas([users, identities, table('nominations')], areas), {
			message:
				'Every table belongs to one area, and these belong to none: nominations, user_identities. Add each to an area in scripts/erd/areas.ts.',
		});
	});

	test('refuses an area naming a table the schema lacks, naming each such table', () => {
		const areas: DiagramArea[] = [{ tables: ['users', 'user_identities', 'memberships'], title: 'All' }];

		assert.throws(() => renderAreas([users, identities], areas), {
			message:
				'Every table an area names is in the schema, and these are not: memberships. Remove each from scripts/erd/areas.ts, or rename it.',
		});
	});

	test('refuses a table that more than one area names, naming each such table', () => {
		const areas: DiagramArea[] = [
			{ tables: ['users', 'user_identities'], title: 'Principals' },
			{ tables: ['users'], title: 'Administrators' },
		];

		assert.throws(() => renderAreas([users, identities], areas), {
			message:
				'Every table belongs to one area, and these belong to more than one: users. Keep each in one area in scripts/erd/areas.ts.',
		});
	});
});

suite('mermaidType', () => {
	test("writes a type of several words in PostgreSQL's short form", () => {
		assert.equal(mermaidType('timestamp with time zone'), 'timestamptz');
		assert.equal(mermaidType('timestamp without time zone'), 'timestamp');
		assert.equal(mermaidType('character varying'), 'varchar');
	});

	test('joins the words of any other type of several words', () => {
		assert.equal(mermaidType('double precision'), 'double_precision');
	});

	test('writes an array type with an _array suffix', () => {
		assert.equal(mermaidType('text[]'), 'text_array');
		assert.equal(mermaidType('timestamp with time zone[]'), 'timestamptz_array');
	});

	test('drops a length or precision, which a diagram type cannot hold', () => {
		assert.equal(mermaidType('character varying(64)'), 'varchar');
		assert.equal(mermaidType('numeric(10,2)'), 'numeric');
	});

	test('keeps a one-word type as it is', () => {
		assert.equal(mermaidType('uuid'), 'uuid');
		assert.equal(mermaidType('jsonb'), 'jsonb');
	});
});
