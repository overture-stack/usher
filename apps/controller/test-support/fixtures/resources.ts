/**
 * Sends registrations at once while the resources table is held, releasing it once each waits on it
 * or when the wait's deadline passes, and fails unless at least one was seen waiting. When every one
 * waits, the race is forced: each is in flight before any can commit. A Controller that serializes
 * registrations in its own process leaves only one waiting, which is as correct; the race is then as
 * close as the Controller allows, and no more than probable.
 *
 * @param harness the harness, whose database is held.
 * @param caller who registers.
 * @param registrations what each registration sends.
 * @returns the answers, in the registrations' order.
 */
export const registeredTogether = async (
	harness: Harness,
	caller: AdminCaller,
	registrations: readonly ResourceRegistration[],
): Promise<readonly AdminResponse[]> => {
	const { migration } = harness.clients;
	const held = await holdTable(harness.database, POLICY_TABLES.resources);
	const answers = Promise.all(registrations.map((sent) => registerResource(caller, sent)));
	const waited = await (async (): Promise<boolean> => {
		try {
			const everyOne = await untilBlocked(migration, answers, {
				count: registrations.length,
			});
			return everyOne || (await blockedBackends(migration)).length > 0;
		} finally {
			await held.release();
		}
	})();
	const settled = await answers;
	assert.ok(waited, 'a registration waits on the held resources table');
	return settled;
};
